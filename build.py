def sources():
    for directory, pattern in ((CONTENT, "*.yaml"), (CSS_DIR, "*.css"), (JS_DIR, "*.js")):
        yield from directory.glob(pattern)
    yield from TEMPLATES.rglob("*.html")
    # Whether a panel gets a clip, a picture or empty water is decided at
    # build time, so a file added to or renamed in media/ is a change too.
    media = ROOT / "media"
    if media.is_dir():
        yield from (p for p in media.rglob("*") if p.is_file())
    for name in SPRITES.values():
        path = SPRITE_DIR / name
        if path.exists():
            yield path


def snapshot():
    return {p: p.stat().st_mtime for p in sources()}


def make_server(port=8000):
    """The local server for --serve: the site folder on localhost:8000.

    Python's own file server sends every file whole. A browser plays a video
    by asking for it a piece at a time (a Range request) and dropping the
    rest when it seeks, loops or scrolls past it; without ranges each of
    those is a whole download cut off halfway, and a traceback in the
    terminal. This one answers ranges, the way a real web host does, and
    lets a browser hang up without complaint."""
    import os
    import re
    from functools import partial
    from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer

    class Handler(SimpleHTTPRequestHandler):
        def log_message(self, *args):
            pass

        def send_head(self):
            want = re.match(r"bytes=(\d*)-(\d*)$", self.headers.get("Range", ""))
            path = self.translate_path(self.path)
            if not want or not os.path.isfile(path):
                return super().send_head()
            size = os.path.getsize(path)
            first, last = want.groups()
            if first:
                start, end = int(first), int(last) if last else size - 1
            else:                             # bytes=-N: the last N bytes
                start, end = max(0, size - int(last or 0)), size - 1
            end = min(end, size - 1)
            if start > end:
                self.send_response(416)
                self.send_header("Content-Range", f"bytes */{size}")
                self.end_headers()
                return None
            f = open(path, "rb")
            f.seek(start)
            self.send_response(206)
            self.send_header("Content-Type", self.guess_type(path))
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
            self.send_header("Content-Length", str(end - start + 1))
            self.end_headers()
            self.remaining = end - start + 1
            return f

        def copyfile(self, source, outputfile):
            left = getattr(self, "remaining", None)
            if left is None:
                return super().copyfile(source, outputfile)
            while left > 0:
                chunk = source.read(min(64 * 1024, left))
                if not chunk:
                    break
                outputfile.write(chunk)
                left -= len(chunk)

        def end_headers(self):
            self.send_header("Accept-Ranges", "bytes")
            super().end_headers()

    class Server(ThreadingHTTPServer):
        daemon_threads = True

        def handle_error(self, request, client_address):
            # the browser hung up mid-file: that's it changing its mind
            if isinstance(sys.exc_info()[1], (ConnectionResetError, BrokenPipeError)):
                return
            super().handle_error(request, client_address)

    return Server(("127.0.0.1", port), partial(Handler, directory=str(ROOT)))


def watch(serve=False):
    import threading

    if serve:
        server = make_server()
        threading.Thread(target=server.serve_forever, daemon=True).start()
        print("Serving http://localhost:8000")

    try:
        build()
    except SystemExit as exc:          # keep watching through a content error
        print(exc)

    print("Watching src/ and media/ for changes. Ctrl+C to stop.")
    last = snapshot()
    try:
        while True:
            time.sleep(0.4)
            now = snapshot()
            if now != last:
                last = now
                print(f"\n[{time.strftime('%H:%M:%S')}] rebuilding")
                try:
                    build()
                except SystemExit as exc:
                    print(exc)
    except KeyboardInterrupt:
        print("\nStopped.")


if __name__ == "__main__":
    args = set(sys.argv[1:])
    if args & {"--serve", "-s"}:
        watch(serve=True)
    elif args & {"--watch", "-w"}:
        watch()
    else:
        build()
