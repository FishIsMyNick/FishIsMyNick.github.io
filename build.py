# **…**, which may hold a *…* of its own. Its closing pair is the first **
# not followed by another star, so in ***  the inner * closes first.
BIGGER = re.compile(r"\*\*(.+?)\*\*(?!\*)")


def emphasis(text):
    """Four marks, usable in any line of content:

        *word*     the accent colour
        **word**   a size up, inside whatever line it sits in
        ^^word^^   raised, for the st in 1^^st^^
        a newline  a line break, so one phrase can be set over two rows

    The text is escaped first, so a stray < in a heading still can't become
    markup — only the asterisks and the line breaks mean anything.

    The accent can sit inside the size-up: **To be the *greatest* fish**,
    or ending together, **To be the *greatest fish*** (the last three
    stars close both).
    """
    from markupsafe import Markup, escape
    out = str(escape(text))
    out = BIGGER.sub(lambda m: f'<span class="bigger">{m.group(1)}</span>', out)
    out = re.sub(r"\*([^*]+)\*",
                 lambda m: f'<span class="accent">{m.group(1)}</span>', out)
    out = re.sub(r"\^\^([^^]+)\^\^", r"<sup>\1</sup>", out)
    # A line the content breaks by hand stays broken. In site.yaml that is a
    # "\n" inside a double-quoted line.
    out = re.sub(r"[ \t]*\r?\n[ \t]*", "<br>", out.strip())
    # ...and so does a typed \n, in a plain or a block line where YAML
    # leaves it as it is.
    out = out.replace("\\n", "<br>")
    return Markup(out)


def prose(text):
    """A paragraph written as a YAML block (`|`): the lines it is wrapped over
    in the file are one paragraph on the page, and a typed `\\n` is where it
    breaks. Then the same marks as `emphasis`."""
    text = re.sub(r"[ \t]*\r?\n[ \t]*", " ", str(text).strip())
    return emphasis(text.replace("\\n", "\n"))


def marks(value):
    """The marks, on everything the templates print. A block (`|`) keeps
    its trailing newline, which is how it is told from a line: a block is a
    paragraph, as `prose`; a line keeps its breaks, as `emphasis`. What a
    filter has already turned into markup (a macro, `emphasis`, `plain`) is
    left as it is."""
    from markupsafe import Markup
    if isinstance(value, Markup) or not isinstance(value, str):
        return value
    return prose(value) if value.endswith("\n") else emphasis(value)


def plain(text):
    """The same text with the marks taken out, for where markup can't go: an
    attribute, the <title>. A line break becomes a space."""
    from markupsafe import Markup, escape
    text = str(text).replace("\\n", " ")
    text = BIGGER.sub(r"\1", text)
    text = re.sub(r"\*([^*]+)\*", r"\1", text)
    text = re.sub(r"\^\^([^^]+)\^\^", r"\1", text)
    return Markup(escape(re.sub(r"\s+", " ", text).strip()))


def render_page(data):
    from jinja2 import Environment, FileSystemLoader, StrictUndefined, TemplateError
    from markupsafe import Markup

    env = Environment(
        loader=FileSystemLoader(str(TEMPLATES)),
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        # Content is escaped on the way in, so an & or a < in a description
        # can't break the page. Templates and macros still emit real markup.
        autoescape=True,
        # A typo in a field name is an error, not a silently empty page.
        undefined=StrictUndefined,
        # The marks work in every field, not just the ones a template asks
        # for. Attributes take `| plain` instead.
        finalize=marks,
    )
    env.filters["emphasis"] = emphasis
    env.filters["accent"] = emphasis      # the name v3.1 used
    env.filters["prose"] = prose
    env.filters["plain"] = plain
    # A missing file still gets a path, so the panel shows as empty water
    # until the picture is added.
    # A link given as a bare url shows its site's name: www.ign.com/… -> ign.com
    env.filters["site_name"] = lambda u: re.sub(r"^www\.", "", re.sub(r"^[a-z]+://", "", str(u)).split("/")[0])
    env.filters["picture"] = lambda n: find_media(n, PICTURE_TYPES) or f"media/{n}.jpg"
    env.filters["pictures"] = find_pictures
    # The preview panels ask for the picture and the clip separately, and
    # get None for whichever isn't there.
    env.filters["still"] = lambda n: find_media(n, PICTURE_TYPES)
    env.filters["clip"] = lambda n: find_media(n, CLIP_TYPES)
    env.filters["model"] = lambda n: find_media(n, MODEL_TYPES)
    env.filters["animations"] = model_animations
    env.filters["clip_label"] = clip_label
    env.filters["first_clip"] = first_clip
    env.filters["logo"] = lambda n: find_media(n, LOGO_TYPES) or f"media/{n}.png"

    try:
        template = env.get_template("base.html")
        return template.render(
            year=date.today().year,
            fish_sprites=load_sprites(),
            aquarium_json=Markup(json.dumps(data["aquarium"], indent=2)),
            **data)
    except TemplateError as exc:
        name = getattr(exc, "filename", None) or "a template"
        line = getattr(exc, "lineno", None)
        where = f"{name}" + (f", line {line}" if line else "")
        sys.exit(f"\nTemplate error in {where}:\n\n  {exc}\n")


def bundle(directory, suffix, comment):
    """Concatenate the parts of a stylesheet or script, in filename order.
    The number prefixes are the order, which is why they exist."""
    files = sorted(directory.glob(f"*{suffix}"))
    if not files:
        sys.exit(f"No {suffix} files in {directory.relative_to(ROOT)}")
    chunks = [comment.format(GENERATED)]
    for path in files:
        chunks.append(f"{comment.format('src/' + str(path.relative_to(SRC)))}\n"
                      + path.read_text(encoding="utf-8").strip("\n"))
    return "\n\n".join(chunks) + "\n", files


def css_variables(aq):
    """The handful of settings CSS needs as values rather than the canvas.
    Written last so they win over the defaults in 01-tokens.css."""
    panels = (aq or {}).get("panels") or {}
    depth = (aq or {}).get("depth") or {}
    bowl = (aq or {}).get("bowl") or {}

    def num(value, fallback):
        try:
            return float(value)
        except (TypeError, ValueError):
            return fallback

    return (
        "\n/* from src/content/aquarium.yaml */\n"
        ":root {\n"
        f"  --panel-opacity: {num(panels.get('opacity'), 0.42)};\n"
        f"  --panel-blur: {num(panels.get('blur'), 14)}px;\n"
        f"  --panel-radius: {num(panels.get('radius'), 26)}px;\n"
        f"  --panel-edge: {num(panels.get('edge'), 0.22)};\n"
        f"  --panel-float: {num(panels.get('float'), 0.25)};\n"
        f"  --bowl-size: {num(bowl.get('width'), 26)}rem;\n"
        f"  --bowl-aspect: {num(bowl.get('aspect'), 0.92)};\n"
        f"  --shallow: {depth.get('shallow_color', '#0d7fa4')};\n"
        f"  --abyss: {depth.get('deep_color', '#02191f')};\n"
        "}\n"
    )


def write_if_changed(path, text):
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def fingerprint(text):
    import hashlib
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]


def build(quiet=False):
    require_dependencies()
    data = load_content()
    validate(data)

    page = render_page(data)
    page = page.replace("<head>", f"<head>\n<!-- {GENERATED} -->", 1)

    css, css_files = bundle(CSS_DIR, ".css", "/* {} */")
    css += css_variables(data["aquarium"])
    js, js_files = bundle(JS_DIR, ".js", "/* {} */")

    # The page asks for each file by a name that changes whenever the file
    # does, so a browser never keeps showing a stylesheet or script it cached
    # from an earlier build.
    page = page.replace('href="styles.css"', f'href="styles.css?v={fingerprint(css)}"', 1)
    page = page.replace('src="script.js"', f'src="script.js?v={fingerprint(js)}"', 1)

    changed = [
        name for name, text in (
            ("index.html", page), ("styles.css", css), ("script.js", js))
        if write_if_changed(ROOT / name, text)
    ]

    if not quiet:
        projects = len(data["professional"]) + len(data["hobby"])
        print(f"Built index.html — {projects} projects, "
              f"{len(css_files)} css parts, {len(js_files)} js parts.")
        sprites = load_sprites()
        print("Fish inlined from {}: {}".format(
            SPRITE_DIR.relative_to(ROOT),
            ", ".join(f"{s['name']} {s['w']}×{s['h']}, {s['bytes'] // 1024}kB"
                      for s in (sprites[k] for k in sorted(sprites)))))
        if changed:
            print("Wrote: " + ", ".join(changed))
        else:
            print("No changes.")
        hidden = data["hidden"]
        if hidden["blocks"] or hidden["spans"]:
            print(f"\nIn progress, left off the page: {len(hidden['blocks'])} block(s), "
                  f"{hidden['spans']} <<…>> span(s)")
            for where in hidden["blocks"]:
                print(f"  {where}")

        gaps = missing_media(data)
        if gaps:
            print(f"\nStill waiting on {len(gaps)} picture(s) in media/ "
                  f"(those panels render empty). Any of "
                  f"{' '.join(PICTURE_TYPES)}, or an .mp4 (or both):")
            for name in gaps:
                print(f"  {name}")

        models = missing_models(data)
        if models:
            print(f"\nAnd {len(models)} 3D model(s) for the Gallery (an empty "
                  f"panel until they're there). Any of {' '.join(MODEL_TYPES)}:")
            for name in models:
                print(f"  {name}")

        logos = missing_logos(data)
        if logos:
            print(f"\nAnd {len(logos)} studio logo(s) (that corner shows the "
                  f"studio's name until they're there). Any of "
                  f"{' '.join(LOGO_TYPES)}:")
            for name in logos:
                print(f"  {name}")
    return True


