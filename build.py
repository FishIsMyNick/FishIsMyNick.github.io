def load_content():
    import yaml

    def read(name):
        path = CONTENT / name
        if not path.exists():
            sys.exit(f"Missing content file: {path.relative_to(ROOT)}")
        try:
            return yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        except yaml.YAMLError as exc:
            sys.exit(f"\n{path.relative_to(ROOT)} is not valid YAML:\n\n{exc}\n")

    data = {
        "site": read("site.yaml"),
        "professional": read("professional.yaml"),
        "hobby": read("hobby.yaml"),
        "experience": read("experience.yaml"),
        "aquarium": read("aquarium.yaml"),
    }
    # The hero panels were called `showcase` before; either name works.
    hero = data["site"].get("hero") if isinstance(data["site"], dict) else None
    if isinstance(hero, dict) and "panels" not in hero and "showcase" in hero:
        hero["panels"] = hero.pop("showcase")
    data["hidden"] = hide_in_progress(data)
    return data


# Two ways to keep something in the content files without it reaching the page:
#
#     in_progress: true     on any block (a project, a role, a skill group, a
#                           hero panel…) leaves the whole block out
#     <<some text>>         inside any line leaves just that text out. A list
#                           item that is nothing but <<…>> is dropped.
#
# Both are taken out before anything is checked, so a hidden block doesn't
# have to be complete yet.
IN_PROGRESS = re.compile(r"<<.*?>>", re.S)


def hide_in_progress(data):
    hidden = {"blocks": [], "spans": 0, "ids": set()}
    gone = object()

    def label(node):
        return node.get("title") or node.get("label") or node.get("heading") \
            or node.get("id") or "a block"

    def clean(node, where):
        if isinstance(node, dict):
            if node.get("in_progress") is True:
                hidden["blocks"].append(f"{where}: {label(node)}")
                if node.get("id"):
                    hidden["ids"].add(node["id"])
                return gone
            out = {}
            for key, value in node.items():
                if key == "in_progress":
                    continue
                value = clean(value, where)
                if value is not gone:
                    out[key] = value
            return out
        if isinstance(node, list):
            items = [clean(item, where) for item in node]
            return [item for item in items if item is not gone]
        if isinstance(node, str) and "<<" in node:
            text, n = IN_PROGRESS.subn("", node)
            hidden["spans"] += n
            # Tidy the gap the text leaves: no doubled spaces, no space
            # before punctuation, no blank line where a paragraph was.
            text = re.sub(r"[ \t]{2,}", " ", text)
            text = re.sub(r" +([.,;:!?])", r"\1", text)
            text = re.sub(r"\n[ \t]*\n(?:[ \t]*\n)+", "\n\n", text)
            text = "\n".join(line.strip() if line.strip() == "" else line.rstrip()
                              for line in text.split("\n"))
            return text if text.strip() else gone
        return node

    for name in ("site", "professional", "hobby", "experience"):
        cleaned = clean(data[name], name + ".yaml")
        data[name] = cleaned if cleaned is not gone else ({} if name in ("site", "experience") else [])

    # A tile on the opening screen that leads to a hidden project goes too.
    shown = {p.get("id") for p in data["professional"] if isinstance(p, dict)}
    hero = data["site"].get("hero")
    if isinstance(hero, dict) and isinstance(hero.get("panels"), list):
        keep = []
        for item in hero["panels"]:
            pid = item.get("project") if isinstance(item, dict) else None
            if pid and pid not in shown and pid in hidden["ids"]:
                hidden["blocks"].append(f"site.yaml: hero panel {item.get('label')}")
            else:
                keep.append(item)
        hero["panels"] = keep
    return hidden


def png_size(raw):
    """Width and height out of a PNG header, so the build can report them and
    the page can be told the shape of the drawing without decoding it."""
    if raw[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    w = int.from_bytes(raw[16:20], "big")
    h = int.from_bytes(raw[20:24], "big")
    return w, h


def load_sprites():
    """Inline both fish drawings into the page, one per direction.

    They go in as data URIs rather than files beside the page, for the same
    reason the artwork always has: the page stays something you can open from
    anywhere — a folder, a USB stick, a web server — with no second request and
    nothing to go missing. A data URI also counts as part of the page itself,
    so the canvas can read the drawing back without the browser treating it as
    somebody else's image.

    The drawings are expected to be trimmed to their ink with a transparent
    background. Nothing is stripped here: what is in the file is what swims.
    """
    out = {}
    for side, name in SPRITES.items():
        path = SPRITE_DIR / name
        if not path.exists():
            sys.exit(
                f"\nMissing the fish artwork: {path.relative_to(ROOT)}"
                "\n\nThere is one drawing per direction — "
                + ", ".join(sorted(SPRITES.values())) +
                " — each trimmed to its ink, on a transparent background.\n")
        raw = path.read_bytes()
        size = png_size(raw)
        if not size:
            sys.exit(f"\n{path.relative_to(ROOT)} is not a PNG.\n")
        out[side] = {
            "uri": "data:image/png;base64," + base64.b64encode(raw).decode("ascii"),
            "w": size[0],
            "h": size[1],
            "bytes": len(raw),
            "name": name,
        }
    return out


def validate(data):
    """Catch the content mistakes that would otherwise show up as a silently
    broken link or a project page that never opens."""
    problems = []

    site = data["site"]
    for field in ("name", "tagline", "intro", "nav", "sections", "contact", "hero"):
        if not site.get(field):
            problems.append(f"site.yaml is missing '{field}'")

    hero = site.get("hero") or {}
    if isinstance(hero, dict) and not hero.get("pitch"):
        problems.append("site.yaml: hero needs a 'pitch' (the lines beside the bowl)")
    pro_ids = {p.get("id") for p in data["professional"] if isinstance(p, dict)} \
        if isinstance(data["professional"], list) else set()
    for i, item in enumerate((hero.get("panels") or []) if isinstance(hero, dict) else [], 1):
        if not isinstance(item, dict) or not item.get("label") or not item.get("project"):
            problems.append(f"site.yaml: hero.panels item {i} needs a 'label' and a 'project'")
        elif item["project"] not in pro_ids:
            problems.append(
                f"site.yaml: hero.panels item {i} ({item['label']}) names project "
                f"'{item['project']}', which isn't an id in professional.yaml")

    aq = data["aquarium"]
    for block in ("bowl", "glass", "fish", "water", "depth", "shoal", "panels", "sound"):
        if not aq.get(block):
            problems.append(f"aquarium.yaml is missing the '{block}' block")
    taps = (aq.get("glass") or {}).get("taps_to_break")
    if taps is not None and (not isinstance(taps, int) or taps < 1):
        problems.append("aquarium.yaml: glass.taps_to_break has to be a whole number, 1 or more")

    seen = {}
    for kind in ("professional", "hobby"):
        entries = data[kind]
        if not isinstance(entries, list):
            problems.append(f"{kind}.yaml should be a list of projects")
            continue

        for i, project in enumerate(entries, 1):
            where = f"{kind}.yaml, project {i}"
            if not isinstance(project, dict):
                problems.append(f"{where}: should be a block of fields")
                continue

            pid = project.get("id")
            name = project.get("title") or pid or f"#{i}"

            if not pid:
                problems.append(f"{where} ({name}): needs an 'id'")
            elif pid in seen:
                problems.append(
                    f"{where} ({name}): id '{pid}' is already used in {seen[pid]}. "
                    "Ids are the page's URL, so they have to be unique.")
            else:
                seen[pid] = kind + ".yaml"

            for field in ("title", "summary"):
                if not project.get(field):
                    problems.append(f"{where} ({name}): needs '{field}'")
            if not (project.get("thumbnail") or project.get("cover") or project.get("media")):
                problems.append(f"{where} ({name}): needs a 'thumbnail' (and, for a "
                                "professional project, a 'cover')")

            if kind == "professional":
                if not project.get("description"):
                    problems.append(f"{where} ({name}): needs 'description'")
                groups = project.get("contributions") or []
                if not isinstance(groups, list):
                    problems.append(f"{where} ({name}): 'contributions' should be a list")
                    groups = []
                for j, group in enumerate(groups, 1):
                    if not isinstance(group, dict) or not isinstance(group.get("items"), list):
                        problems.append(f"{where} ({name}): contribution {j} needs "
                                        "'items', a list of what you built")
            else:
                for field in ("overview", "technologies"):
                    if not project.get(field):
                        problems.append(f"{where} ({name}): needs '{field}'")
                for j, item in enumerate(project.get("features") or [], 1):
                    if not item.get("media"):
                        problems.append(f"{where} ({name}): feature {j} needs 'media'")

            models = project.get("gallery") or []
            if not isinstance(models, list):
                problems.append(f"{where} ({name}): 'gallery' should be a list of 3D models")
                models = []
            for j, item in enumerate(models, 1):
                if not isinstance(item, dict) or not (item.get("model") or item.get("animation")):
                    problems.append(f"{where} ({name}): gallery item {j} needs 'model' "
                                    "or 'animation' (a .glb or .gltf in media/, "
                                    "named without its extension)")
                    continue
                stem = item.get("animation") or item.get("model")
                clips = model_animations(stem)
                if item.get("animation") and find_media(stem, MODEL_TYPES) and not clips:
                    problems.append(f"{where} ({name}): gallery item {j}: {stem} has no "
                                    "animations in it; use 'model' for a still one")
                for field in ("play",):
                    if item.get(field) and clips and item[field] not in clips:
                        problems.append(f"{where} ({name}): gallery item {j}: no animation "
                                        f"called {item[field]!r} in {stem} (it has "
                                        f"{', '.join(clips)})")
                for clip in item.get("animations") or item.get("clips") or []:
                    if clips and clip not in clips:
                        problems.append(f"{where} ({name}): gallery item {j}: no animation "
                                        f"called {clip!r} in {stem} (it has "
                                        f"{', '.join(clips)})")

            links = project.get("links") or []
            if not isinstance(links, list):
                problems.append(f"{where} ({name}): 'links' should be a list")
                links = []
            for j, link in enumerate(links, 1):
                url = link.get("url") if isinstance(link, dict) else link
                if not isinstance(url, str) or not re.match(r"^(https?://|mailto:)", url):
                    problems.append(f"{where} ({name}): link {j} needs a 'url' "
                                    "starting with https://")
                rating = link.get("rating") if isinstance(link, dict) else None
                if rating is not None and not re.match(r"^\s*\d+(\.\d+)?\s*/\s*\d+(\.\d+)?\s*$", str(rating)):
                    problems.append(f"{where} ({name}): link {j} has rating {rating!r}; "
                                    "write it as score/out-of, e.g. 8/10")

    exp = data["experience"]
    if not exp.get("roles"):
        problems.append("experience.yaml is missing 'roles'")
    for i, group in enumerate(exp.get("skills") or [], 1):
        if not group.get("heading") or not group.get("items"):
            problems.append(f"experience.yaml, skill group {i}: needs 'heading' and 'items'")

    if problems:
        sys.exit("\nThe content needs fixing:\n\n" +
                 "\n".join("  - " + p for p in problems) + "\n")


def find_media(name, types):
    """The file in media/ at <name> with one of these extensions, as the
    page's path to it — or None when there isn't one yet."""
    folder = ROOT / "media"
    if not name or not folder.is_dir():
        return None
    # The name can sit in a folder (professional/llamaware/cover), so every
    # file under media/ is matched by its path from there.
    found = {}
    for f in folder.rglob("*"):
        if f.is_file():
            rel = f.relative_to(folder).as_posix()
            found[rel.lower()] = rel
    for ext in types:
        real = found.get(f"{name}{ext}".lower())
        if real:
            return f"media/{real}"
    return None


def find_pictures(folder):
    """Every picture directly inside media/<folder>/, in filename order, as
    the page's paths to them — empty when there are none yet."""
    path = ROOT / "media" / str(folder).strip("/")
    if not folder or not path.is_dir():
        return []
    return [f"media/{f.relative_to(ROOT / 'media').as_posix()}"
            for f in sorted(path.iterdir(), key=lambda f: f.name.lower())
            if f.is_file() and f.suffix.lower() in PICTURE_TYPES]


def missing_media(data):
    """Not an error — just a list of clips not added yet, so you can see what's
    still outstanding. Panels without a file render as empty water."""
    wanted = []
    for kind in ("professional", "hobby"):
        for project in data[kind]:
            for field in ("hero", "thumbnail", "cover", "media"):
                wanted.append(project.get(field))
            if project.get("contribution_media"):
                wanted.append(project["contribution_media"])
            for group in project.get("contributions") or []:
                if isinstance(group, dict) and group.get("media"):
                    wanted.append(group["media"])
            for item in project.get("features") or []:
                wanted.append(item.get("media"))
            for item in project.get("gallery") or []:
                if isinstance(item, dict) and item.get("poster"):
                    wanted.append(item["poster"])
    hero = data["site"].get("hero")
    folders = []
    for item in (hero.get("panels") or []) if isinstance(hero, dict) else []:
        if isinstance(item, dict):
            wanted.append(item.get("media"))
            if item.get("photos") and not find_pictures(item["photos"]):
                folders.append(item["photos"].rstrip("/") + "/  (a folder, any pictures)")
    # A clip alone fills a panel too (its first frame is the still). A name
    # ending in / is a folder, filled by any picture in it.
    def there(n):
        if str(n).endswith("/"):
            return find_pictures(n)
        return find_media(n, PICTURE_TYPES + CLIP_TYPES)
    return [n + ("  (a folder, any pictures)" if str(n).endswith("/") else "")
            for n in dict.fromkeys(filter(None, wanted)) if not there(n)] + folders


def model_animations(name):
    """The names of the animations inside a model in media/, in the order
    the file has them — empty when it has none or isn't there yet. Read
    from the glTF's JSON: the first chunk of a .glb, or the whole .gltf."""
    path = find_media(name, MODEL_TYPES)
    if not path:
        return []
    try:
        raw = (ROOT / path).read_bytes()
        if raw[:4] == b"glTF":
            size = int.from_bytes(raw[12:16], "little")
            gltf = json.loads(raw[20:20 + size])
        else:
            gltf = json.loads(raw)
    except (OSError, ValueError):
        return []
    return [a.get("name") or f"Animation {i}"
            for i, a in enumerate(gltf.get("animations") or [], 1)]


def clip_label(name):
    """An animation's name as a button says it: JumpHorStatic and
    jump_hor_static both read "Jump Hor Static"."""
    words = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", str(name)).replace("_", " ").split()
    return " ".join(w[:1].upper() + w[1:] for w in words)


def first_clip(item):
    """The animation a gallery model starts on: the item's `play`, else one
    called Idle, else the first in the file. None for a still model."""
    clips = model_animations(item.get("animation") or item.get("model"))
    if not clips:
        return None
    if item.get("play") in clips:
        return item["play"]
    return next((c for c in clips if c.lower() == "idle"), clips[0])


def missing_models(data):
    """The same, for the 3D models in the Gallery sections. A missing one
    leaves an empty panel."""
    wanted = [item.get("animation") or item.get("model")
              for kind in ("professional", "hobby") for project in data[kind]
              for item in (project.get("gallery") or []) if isinstance(item, dict)]
    return [n for n in dict.fromkeys(filter(None, wanted))
            if not find_media(n, MODEL_TYPES)]


def missing_logos(data):
    """The same, for the studio marks in the corner of a split thumbnail. A
    missing one shows the studio's name instead."""
    wanted = [p.get("logo") for p in data["professional"] if p.get("logo")]
    return [n for n in dict.fromkeys(wanted)
            if not find_media(n, LOGO_TYPES)]


