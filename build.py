#!/usr/bin/env python3
"""
Build the portfolio.

Reads the content in src/content, pours it into the templates in
src/templates, and writes one static page plus one stylesheet and one script:

    src/content/*.yaml   ─┐
    src/templates/**     ─┼─►  index.html
    src/assets/css/*.css ─┼─►  styles.css
    src/assets/js/*.js   ─┴─►  script.js

Those three files, plus media/, are the whole site. Nothing else needs to be
uploaded anywhere.

    python build.py            build once
    python build.py --watch    rebuild whenever a source or media file changes
    python build.py --serve    the same, with a local server on :8000

v3.1 adds one more content file: src/content/aquarium.yaml. Every number the
bowl, the glass, the water and the fish use lives there. It is written into the
page as JSON, so nothing in the script has a hard-coded feel to it.
"""

from __future__ import annotations

import base64
import json
import re
import sys
import time
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
CONTENT = SRC / "content"
TEMPLATES = SRC / "templates"
CSS_DIR = SRC / "assets" / "css"
JS_DIR = SRC / "assets" / "js"
SPRITE_DIR = SRC / "assets" / "img"

# One drawing per direction, rather than one drawing mirrored. v3.4.
SPRITES = {"left": "fish-left.png", "right": "fish-right.png"}

# What a picture in media/ may be saved as, in the order they're looked for.
# The yaml names the file without its extension; the build finds whichever
# one is there. Case doesn't matter (.JPG is found too).
PICTURE_TYPES = (".jpg", ".jpeg", ".png", ".webp", ".avif")
CLIP_TYPES = (".mp4",)
LOGO_TYPES = (".png", ".svg", ".webp", ".avif")
MODEL_TYPES = (".glb", ".gltf")

GENERATED = "This file is generated by build.py. Edit the files in src/ instead."


